    print(f"Reading dataset: {filename}")
    if os.path.exists(filename):
        feats, labels = load_amvr_dataset(filename)
        print("Features shape:", feats.shape)
        print("Labels value counts for IMV target (0: 1/4, 1: 1/2, 2: 1, 3: 4):")
